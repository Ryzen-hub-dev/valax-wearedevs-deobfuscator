class DiagnosticError extends Error {
  constructor(category, message, details = {}) {
    super(message);
    this.name = 'DiagnosticError';
    this.category = category;
    this.details = details;
  }
}

function classifyError(err) {
  if (err instanceof DiagnosticError) {
    return { category: err.category, message: err.message, details: err.details };
  }

  const msg = err.message || String(err);
  if (msg.includes('Unexpected token') || msg.includes('Expected') || msg.includes('parse')) {
    return { category: FailureCategory.PARSER_FAILURE, message: msg };
  }
  if (msg.includes('CFG') || msg.includes('block') || msg.includes('edge')) {
    return { category: FailureCategory.CFG_FAILURE, message: msg };
  }
  if (msg.includes('string') || msg.includes('decode') || msg.includes('alphabet')) {
    return { category: FailureCategory.STRING_RECOVERY_FAILURE, message: msg };
  }
  if (msg.includes('constant') || msg.includes('evaluat')) {
    return { category: FailureCategory.CONSTANT_FAILURE, message: msg };
  }
  if (msg.includes('closure') || msg.includes('context')) {
    return { category: FailureCategory.CLOSURE_FAILURE, message: msg };
  }

  return { category: FailureCategory.UNKNOWN_VARIANT, message: msg };
}

